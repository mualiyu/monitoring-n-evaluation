<?php

declare(strict_types=1);

namespace App\Livewire\Tenant\Reporting;

use App\Enums\ReportingCadence;
use App\Enums\ReportObligationStatus;
use App\Models\Project;
use App\Models\ReportingPeriod;
use App\Models\ReportObligation;
use App\Models\User;
use App\Support\SettingsRepository;
use Illuminate\Contracts\Pagination\LengthAwarePaginator;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Support\Carbon;
use Illuminate\Support\Collection;
use Illuminate\View\View;
use Livewire\Attributes\Computed;
use Livewire\Attributes\Layout;
use Livewire\Attributes\Url;
use Livewire\Component;
use Livewire\WithPagination;

/**
 * The M&E calendar (progress-reporting.md §6): the statutory windows, their
 * deadlines, and what this workspace owes against each one.
 *
 * NO DEADLINE IS COMPUTED HERE. Windows carry their own `due_at`, generated by
 * GenerateReportingPeriods from the configured rules; an obligation carries the
 * deadline it was given, snapshotted at generation; and the countdown is
 * ReportObligation::daysToDue(), the same definition the reminder ladder uses,
 * counted on the instance's wall clock. A screen that said "due in 3 days"
 * while the engine was sending the 2-day reminder would destroy trust in both.
 * Even "due soon" is not a literal: it is the longest rung of the configured
 * reminder ladder, read through SettingsRepository — so the calendar highlights
 * exactly the window in which the platform starts chasing.
 *
 * Read-only. Waiving an obligation is a decision with a permanent record and
 * lives on the reporting desk, behind `reports.waive`.
 */
#[Layout('layouts::tenant')]
class ReportingCalendar extends Component
{
    use WithPagination;

    /** Which rhythm of the statutory calendar is on screen. */
    #[Url(except: '')]
    public string $cadence = '';

    /** The window whose per-project detail is open. */
    #[Url(as: 'period', except: '')]
    public string $periodId = '';

    /** ULID, never a primary key — this value is bookmarked and pasted. */
    #[Url(as: 'project', except: '')]
    public string $projectUlid = '';

    public function mount(): void
    {
        $this->authorize('viewAny', ReportObligation::class);
    }

    public function updatedCadence(): void
    {
        // The chosen window belongs to the old cadence and would not be in the
        // new list — an empty drill-down under a populated calendar reads as a
        // bug rather than as a filter.
        $this->periodId = '';
        $this->resetPage();
    }

    public function updatedProjectUlid(): void
    {
        $this->resetPage();
    }

    public function showPeriod(int $periodId): void
    {
        $this->periodId = (string) $periodId;
        $this->resetPage();
    }

    public function clearFilters(): void
    {
        $this->reset(['cadence', 'projectUlid']);
        $this->resetPage();
    }

    public function hasFilters(): bool
    {
        return $this->cadence !== '' || $this->projectUlid !== '';
    }

    private function user(): User
    {
        /** @var User $user */
        $user = auth()->user();

        return $user;
    }

    /* ---------------------------------------------------------------- */
    /* Configured deadline policy — never a literal */
    /* ---------------------------------------------------------------- */

    /**
     * The reminder ladder, in days before the deadline.
     *
     * @return list<int>
     */
    public function reminderLadder(): array
    {
        return app(SettingsRepository::class)->ints('reporting', 'reminder_days_before', [7, 3, 1]);
    }

    /**
     * When "due soon" starts: the first rung of the ladder, i.e. the moment
     * the platform itself starts chasing. Falls back to the window's own
     * deadline (0 days) if an instance has switched reminders off entirely.
     */
    public function leadDays(): int
    {
        $ladder = $this->reminderLadder();

        return $ladder === [] ? 0 : max($ladder);
    }

    /**
     * Days past due at which an unmet obligation escalates — MDA admin first,
     * then state oversight.
     *
     * @return list<int>
     */
    public function escalationLadder(): array
    {
        return app(SettingsRepository::class)->ints('reporting', 'overdue_escalation_days', [1, 7]);
    }

    /* ---------------------------------------------------------------- */
    /* The calendar */
    /* ---------------------------------------------------------------- */

    /**
     * The windows worth showing: every one this workspace owes (or owed) a
     * return for, plus the windows currently open — so a freshly provisioned
     * MDA still sees the calendar it is about to be measured against instead
     * of an empty screen.
     *
     * @return Collection<int, ReportingPeriod>
     */
    #[Computed]
    public function periods(): Collection
    {
        $owed = ReportObligation::query()->visibleTo($this->user())->select('reporting_period_id');

        return ReportingPeriod::query()
            ->where(fn (Builder $q) => $q->whereIn('id', $owed)->orWhere(
                fn (Builder $open) => $open->where('opens_at', '<=', now())
                    ->where(fn (Builder $live) => $live->whereNull('closes_at')->orWhere('closes_at', '>', now())),
            ))
            ->when(
                $this->cadence !== '' && ReportingCadence::tryFrom($this->cadence) instanceof ReportingCadence,
                fn (Builder $q) => $q->where('cadence', $this->cadence),
            )
            ->orderByDesc('period_start')
            ->limit(24)
            // Whole models: isOpen()/isOverdue() read opens_at, closes_at and
            // due_at, and a partial select would hand them a model with holes.
            ->get();
    }

    /** The window whose detail is open — the most recent one unless chosen. */
    #[Computed]
    public function period(): ?ReportingPeriod
    {
        if ($this->periodId !== '') {
            $chosen = $this->periods()->firstWhere('id', (int) $this->periodId);

            if ($chosen instanceof ReportingPeriod) {
                return $chosen;
            }
        }

        return $this->periods()->first();
    }

    /** The window before the one on screen, for the switcher. */
    #[Computed]
    public function previousPeriod(): ?ReportingPeriod
    {
        $current = $this->period();

        return $current === null
            ? null
            : $this->periods()->first(fn (ReportingPeriod $p): bool => $p->period_start->lessThan($current->period_start));
    }

    /** The window after the one on screen, for the switcher. */
    #[Computed]
    public function nextPeriod(): ?ReportingPeriod
    {
        $current = $this->period();

        return $current === null
            ? null
            : $this->periods()->last(fn (ReportingPeriod $p): bool => $p->period_start->greaterThan($current->period_start));
    }

    /**
     * This workspace's record against every window on screen, in ONE grouped
     * query — the same shape (and the same definitions) as the state
     * compliance board, so the two can never disagree about a month.
     *
     * @return array<int, array{expected: int, met: int, due: int, overdue: int, waived: int, missed: int}>
     */
    #[Computed]
    public function summary(): array
    {
        $ids = $this->periods()->modelKeys();

        if ($ids === []) {
            return [];
        }

        $now = Carbon::now();

        $rows = ReportObligation::query()
            ->visibleTo($this->user())
            ->whereIn('reporting_period_id', $ids)
            ->toBase()
            ->selectRaw('reporting_period_id')
            ->selectRaw('COUNT(*) as expected')
            ->selectRaw('COUNT(CASE WHEN status = ? THEN 1 END) as met', [ReportObligationStatus::Fulfilled->value])
            ->selectRaw('COUNT(CASE WHEN status = ? AND due_at >= ? THEN 1 END) as due', [ReportObligationStatus::Pending->value, $now])
            ->selectRaw('COUNT(CASE WHEN status = ? AND due_at < ? THEN 1 END) as overdue', [ReportObligationStatus::Pending->value, $now])
            ->selectRaw('COUNT(CASE WHEN status = ? THEN 1 END) as waived', [ReportObligationStatus::Waived->value])
            ->selectRaw('COUNT(CASE WHEN status = ? THEN 1 END) as missed', [ReportObligationStatus::Missed->value])
            ->groupBy('reporting_period_id')
            ->get();

        $summary = [];

        foreach ($rows as $row) {
            $summary[(int) $row->reporting_period_id] = [
                'expected' => (int) $row->expected,
                'met' => (int) $row->met,
                'due' => (int) $row->due,
                'overdue' => (int) $row->overdue,
                'waived' => (int) $row->waived,
                'missed' => (int) $row->missed,
            ];
        }

        return $summary;
    }

    /**
     * A window's counts, with zeroes for a window nothing has been generated
     * against yet — a missing key would make the calendar row render blank.
     *
     * @return array{expected: int, met: int, due: int, overdue: int, waived: int, missed: int}
     */
    public function countsFor(ReportingPeriod $period): array
    {
        return $this->summary()[$period->id] ?? [
            'expected' => 0, 'met' => 0, 'due' => 0, 'overdue' => 0, 'waived' => 0, 'missed' => 0,
        ];
    }

    /**
     * The workspace-wide figures above the calendar. Unfiltered on purpose:
     * they answer "are we behind", not "what am I looking at".
     *
     * @return array{outstanding: int, due_soon: int, overdue: int, waived: int}
     */
    #[Computed]
    public function stats(): array
    {
        $now = Carbon::now();
        $soon = $now->copy()->addDays($this->leadDays());

        $row = ReportObligation::query()
            ->visibleTo($this->user())
            ->toBase()
            ->selectRaw('COUNT(CASE WHEN status = ? THEN 1 END) as outstanding', [ReportObligationStatus::Pending->value])
            ->selectRaw(
                'COUNT(CASE WHEN status = ? AND due_at >= ? AND due_at <= ? THEN 1 END) as due_soon',
                [ReportObligationStatus::Pending->value, $now, $soon],
            )
            ->selectRaw('COUNT(CASE WHEN status = ? AND due_at < ? THEN 1 END) as overdue', [ReportObligationStatus::Pending->value, $now])
            ->selectRaw('COUNT(CASE WHEN status = ? THEN 1 END) as waived', [ReportObligationStatus::Waived->value])
            ->first();

        return [
            'outstanding' => (int) ($row->outstanding ?? 0),
            'due_soon' => (int) ($row->due_soon ?? 0),
            'overdue' => (int) ($row->overdue ?? 0),
            'waived' => (int) ($row->waived ?? 0),
        ];
    }

    /* ---------------------------------------------------------------- */
    /* Per-project drill-down */
    /* ---------------------------------------------------------------- */

    /**
     * What each project owes for the window on screen.
     *
     * @return LengthAwarePaginator<int, ReportObligation>
     */
    #[Computed]
    public function obligations(): LengthAwarePaginator
    {
        $period = $this->period();

        return ReportObligation::query()
            ->visibleTo($this->user())
            // A null window (nothing generated yet) must match nothing rather
            // than every obligation the workspace has ever had.
            ->where('reporting_period_id', $period?->id ?? 0)
            ->when($this->projectUlid !== '', fn (Builder $q) => $q->whereIn('project_id', $this->filteredProject()))
            ->with([
                'project:id,ulid,title,reference,physical_progress',
                'progressReport:id,ulid,status',
            ])
            ->orderBy('due_at')
            ->orderBy('id')
            ->paginate(25);
    }

    /** @return Builder<Project> */
    private function filteredProject(): Builder
    {
        return Project::query()->where('ulid', $this->projectUlid)->select('id');
    }

    /** @return array<string, string> */
    #[Computed]
    public function projectOptions(): array
    {
        return Project::query()
            ->visibleTo($this->user())
            ->orderBy('title')
            ->pluck('title', 'ulid')
            ->all();
    }

    /** @return array<string, string> */
    #[Computed]
    public function cadenceOptions(): array
    {
        return collect(ReportingCadence::cases())
            ->mapWithKeys(fn (ReportingCadence $case) => [$case->value => $case->label()])
            ->all();
    }

    /**
     * A window's state in one word, derived — never stored. A status column on
     * a statutory deadline needs a cron to stay true, and a stale one is a
     * compliance defect.
     */
    public function windowState(ReportingPeriod $period): string
    {
        return match (true) {
            $period->isUpcoming() => 'upcoming',
            $period->isClosed() => 'closed',
            $period->isOverdue() => 'overdue',
            default => 'open',
        };
    }

    public function render(): View
    {
        return view('livewire.tenant.reporting.reporting-calendar');
    }
}
